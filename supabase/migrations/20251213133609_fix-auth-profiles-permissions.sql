-- 1) Ensure auth admin can use schema + insert profiles (fixes "permission denied")
grant usage on schema public to supabase_auth_admin;
grant insert, select, update on table public.profiles to supabase_auth_admin;

-- 2) Create/replace trigger function as SECURITY DEFINER (standard pattern)
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email, full_name)
  values (
    new.id,
    new.email,
    new.raw_user_meta_data->>'full_name'
  )
  on conflict (id) do update
    set email = excluded.email,
        full_name = excluded.full_name;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();
